#!/usr/bin/env node
/**
 * Builds a single runnable Frida agent from the split sources.
 *
 * The split is loss-free: every top-level statement of the original bundle
 * lives in exactly one file under src/, and src/manifest.json keeps the load
 * order required by eager dependencies (class `extends`, top-level `new`,
 * top-level calls). Statements inside one file always keep their original
 * relative order.
 *
 *   node build.js            -> dist/rythm-agent.js
 *   node build.js --check    -> build and syntax-check the result
 */
const fs = require('fs');
const path = require('path');

const root = __dirname;
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'src/manifest.json'), 'utf8'));
const outFile = path.join(root, 'dist', 'rythm-agent.js');

const parts = [
  '// rythm agent — generated by build.js, do not edit by hand',
  `// modules: ${manifest.order.length}`,
  '',
];

for (const mod of manifest.order) {
  const file = path.join(root, 'src', mod + '.js');
  if (!fs.existsSync(file)) throw new Error('missing module file: ' + file);
  parts.push(`// ---------------------------------------------------------------------------`);
  parts.push(`// ${mod}.js`);
  parts.push(`// ---------------------------------------------------------------------------`);
  parts.push(fs.readFileSync(file, 'utf8').replace(/\s+$/, ''));
  parts.push('');
}

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, parts.join('\n'));
const lines = fs.readFileSync(outFile, 'utf8').split('\n').length;
console.log(`built ${path.relative(root, outFile)} — ${lines} lines`);
